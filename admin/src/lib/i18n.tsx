const MESSAGES: Record<Language, Record<string, string>> = { en: EN, ru: RU };
const STORAGE_KEY = 'vishar-crm-language';

export function translate(language: Language, key: string, params: Params = {}): string {
  const template = MESSAGES[language][key] ?? MESSAGES.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : match
  );
}

export function humanise(value: string): string {
  return value.replace(/[._]/g, ' ').replace(/\s+/g, ' ').trim();
}

function initialLanguage(): Language {
  try {
    const saved = window.localStorage.getItem(STORAGE_KEY);
    if (saved === 'en' || saved === 'ru') return saved;
  } catch {
    // Storage can be unavailable in private or hardened browser contexts.
  }
  return typeof navigator !== 'undefined' && navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

interface LanguageContextValue {
  language: Language;
  locale: string;
  setLanguage: (language: Language) => void;
  t: (key: string, params?: Params) => string;
  label: (group: string, value: string | null | undefined) => string;
}

const defaultValue: LanguageContextValue = {
  language: 'en',
  locale: 'en-GB',
  setLanguage: () => undefined,
  t: (key, params) => translate('en', key, params),
  label: (group, value) => value ? translate('en', `${group}.${value}`) === `${group}.${value}` ? humanise(value) : translate('en', `${group}.${value}`) : '—',
};

const LanguageContext = createContext<LanguageContextValue>(defaultValue);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(initialLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
    try {
      window.localStorage.setItem(STORAGE_KEY, language);
    } catch {
      // The selected language still applies for this session.
    }
  }, [language]);

  const t = useCallback((key: string, params?: Params) => translate(language, key, params), [language]);
  const label = useCallback((group: string, value: string | null | undefined) => {
    if (!value) return '—';
    const key = `${group}.${value}`;
    const translated = translate(language, key);
    return translated === key ? humanise(value) : translated;
  }, [language]);

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    locale: language === 'ru' ? 'ru-RU' : 'en-GB',
    setLanguage,
    t,
    label,
  }), [language, t, label]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage(): LanguageContextValue {
  return useContext(LanguageContext);
}
