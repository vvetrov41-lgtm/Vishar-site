// Keeps the SQL port of booking form v2 normalisation equal to the Worker.
//
//  1. crm_private.enquiry_v2_catalogue() must equal config/enquiry-form-v2.json
//     (without "note").
//  2. supabase/tests/331_enquiry_v2_sql_parity.sql is generated from the
//     Worker's own parseProjectDetails + deriveLegacyFields for a fixed set of
//     inputs. pgTAP then proves the SQL normaliser returns the same values.
//
// Run with --write to regenerate the pgTAP file after a deliberate change.

import assert from 'node:assert/strict';
import { readFileSync, writeFileSync } from 'node:fs';
import { parseProjectDetails, deriveLegacyFields } from '../workers/lib/enquiry-v2.js';

const MIGRATION = 'supabase/migrations/20261009210000_structured_enquiry_editing.sql';
const PARITY = 'supabase/tests/331_enquiry_v2_sql_parity.sql';

const config = JSON.parse(readFileSync('config/enquiry-form-v2.json', 'utf8'));
delete config.note;
const migration = readFileSync(MIGRATION, 'utf8');
const literal = migration.match(/create or replace function crm_private\.enquiry_v2_catalogue\(\)[\s\S]*?select '([^']*)'::jsonb;/);
assert.ok(literal, 'catalogue literal not found in migration');
assert.deepEqual(JSON.parse(literal[1]), config, 'SQL catalogue differs from config/enquiry-form-v2.json');

const fixtures = [
  ['full sleeve with forearm cover-up and a colour leg tattoo', {
    areas: [
      { region: 'arm', placements: ['full_sleeve', 'forearm'], work: ['cover_up'] },
      { region: 'leg', placements: ['calf'], work: ['new'] },
    ],
    styles: ['colour'],
    sizeNotes: '  Whole left arm, calf about 15 cm  ',
    existingDetails: 'Old tribal band on the forearm',
  }],
  ['single new black and grey forearm', {
    areas: [{ region: 'arm', placements: ['forearm'], work: ['new'] }],
    styles: ['black_grey'],
  }],
  ['full back rework in both styles', {
    areas: [{ region: 'back', placements: ['full_back'], work: ['rework'] }],
    styles: ['black_grey', 'colour'],
    existingDetails: 'Faded piece from 2015',
  }],
  ['other region, not sure of style, existing details dropped for new work', {
    areas: [{ region: 'other', placements: [], otherPlacement: 'Inner lip', work: ['new'] }],
    styles: ['not_sure'],
    existingDetails: 'ignored because nothing existing',
  }],
  ['other arm placement extension plus new fingers', {
    areas: [
      { region: 'arm', placements: ['other'], otherPlacement: 'Back of the arm', work: ['extension'] },
      { region: 'hand', placements: ['fingers'], work: ['new'] },
    ],
    styles: ['colour', 'black_grey'],
  }],
  ['ribs extension and rework, colour', {
    areas: [{ region: 'chest_ribs', placements: ['ribs', 'collarbone'], work: ['extension', 'rework'] }],
    styles: ['colour'],
    sizeNotes: 'Palm\u0007 sized',
  }],
  ['half leg sleeve new', {
    areas: [{ region: 'leg', placements: ['half_leg_sleeve', 'knee'], work: ['new'] }],
    styles: ['black_grey'],
  }],
];

const invalid = [
  ['unknown region', { areas: [{ region: 'tail', placements: [], work: ['new'] }], styles: ['colour'] }],
  ['two sleeve lengths', { areas: [{ region: 'arm', placements: ['half_sleeve', 'full_sleeve'], work: ['new'] }], styles: ['colour'] }],
  ['new combined with cover-up', { areas: [{ region: 'arm', placements: ['forearm'], work: ['new', 'cover_up'] }], styles: ['colour'] }],
  ['no work', { areas: [{ region: 'arm', placements: ['forearm'], work: [] }], styles: ['colour'] }],
  ['no placement', { areas: [{ region: 'arm', placements: [], work: ['new'] }], styles: ['colour'] }],
  ['other without text', { areas: [{ region: 'other', placements: [], work: ['new'] }], styles: ['colour'] }],
  ['no style', { areas: [{ region: 'arm', placements: ['forearm'], work: ['new'] }], styles: [] }],
  ['not sure with another style', { areas: [{ region: 'arm', placements: ['forearm'], work: ['new'] }], styles: ['not_sure', 'colour'] }],
  ['repeated region', { areas: [
    { region: 'arm', placements: ['forearm'], work: ['new'] },
    { region: 'arm', placements: ['wrist'], work: ['new'] },
  ], styles: ['colour'] }],
  ['no areas', { areas: [], styles: ['colour'] }],
];

const q = (value) => `'${String(value).replaceAll("'", "''")}'`;
const lines = [
  '-- 331_enquiry_v2_sql_parity.sql',
  '-- GENERATED by scripts/test-enquiry-v2-sql-catalogue.mjs --write. Do not edit by hand.',
  '-- Expected values come from workers/lib/enquiry-v2.js; the SQL normaliser',
  '-- (crm_private.normalise_enquiry_project_input) must return the same.',
  '',
  'begin;',
  'select no_plan();',
  '',
];

for (const [name, input] of fixtures) {
  const parsed = parseProjectDetails(JSON.stringify(input));
  const legacy = deriveLegacyFields(parsed);
  const expected = {
    project_details: parsed.details,
    project_type: legacy.projectType,
    placement: legacy.placement,
    approximate_size: legacy.size,
    cover_up: legacy.coverUp,
  };
  lines.push(
    `select is(crm_private.normalise_enquiry_project_input(${q(JSON.stringify(input))}::jsonb),`,
    `  ${q(JSON.stringify(expected))}::jsonb,`,
    `  ${q(`parity: ${name}`)});`,
    '',
  );
}

for (const [name, input] of invalid) {
  assert.throws(() => parseProjectDetails(JSON.stringify(input)), undefined, `Worker must reject: ${name}`);
  lines.push(
    `select throws_ok(${q(`select crm_private.normalise_enquiry_project_input(${q(JSON.stringify(input))}::jsonb)`)},`,
    `  '22023', null, ${q(`parity: Worker and SQL both reject ${name}`)});`,
    '',
  );
}

lines.push('select * from finish(true);', 'rollback;', '');
const generated = lines.join('\n');

if (process.argv.includes('--write')) {
  writeFileSync(PARITY, generated);
  console.log(`Wrote ${PARITY}`);
} else {
  assert.equal(readFileSync(PARITY, 'utf8'), generated, `${PARITY} is stale; run node scripts/test-enquiry-v2-sql-catalogue.mjs --write`);
  console.log('Booking form v2 SQL catalogue and Worker parity fixtures are current');
}
