import assert from 'node:assert/strict';
import {parseWake,receiveWake,consumeWake,handleDrainWake,isWakeRequest} from '../workers/lib/outbox-wake.js';
const now=Date.parse('2026-11-25T19:00:00Z');
const key='a'.repeat(64);
const wakeUrl='https://outbox-wake.vishartattoo.com/internal/outbox/wake';
const payload={lane:'calendar',due_at:new Date(now).toISOString()};
assert.deepEqual(parseWake(payload,now),{lane:'calendar',delaySeconds:0});
assert.deepEqual(parseWake({...payload,due_at:new Date(now+10000).toISOString()},now),{lane:'calendar',delaySeconds:11});
for(const bad of [{...payload,lane:'__proto__'},{...payload,client_id:'secret'},{...payload,due_at:'bad'},{...payload,due_at:new Date(now+301000).toISOString()}])assert.equal(parseWake(bad,now),null);
const sent=[];
const env={VISHAR_ENVIRONMENT:'production',OUTBOX_WAKE_ENABLED:'true',OUTBOX_WAKE_SECRET:key,OUTBOX_WAKE_QUEUE:{send:async(...args)=>sent.push(args)}};
const request=(body=payload,secret=key,url=wakeUrl)=>new Request(url,{method:'POST',headers:{'content-type':'application/json','x-outbox-wake-key':secret},body:JSON.stringify(body)});
assert.equal((await receiveWake(request(),env,now)).status,202);
assert.deepEqual(sent,[[{lane:'calendar'},{delaySeconds:0}]]);
assert.equal((await receiveWake(request(payload,'b'.repeat(64)),env,now)).status,401);
assert.equal((await receiveWake(request(),{...env,OUTBOX_WAKE_ENABLED:'false'},now)).status,404);
assert.equal((await receiveWake(request(payload,key,'https://example.com/internal/outbox/wake'),env,now)).status,404);
assert.equal((await receiveWake(request({...payload,extra:'x'.repeat(300)}),env,now)).status,413);
const calls=[];let ack=0,retry=0;
const msg=lane=>({body:{lane},ack(){ack++;},retry(options){assert.equal(options.delaySeconds,15);retry++;}});
const service={fetch:async(url,init)=>{calls.push([url,init.method]);return Response.json({ok:true});}};
await consumeWake({messages:[msg('calendar'),msg('calendar'),msg('whatsapp'),msg('instagram'),msg('email'),msg('bad')]},{...env,CALENDAR_SERVICE:service,WHATSAPP_SERVICE:service,INSTAGRAM_SERVICE:service,GMAIL_SERVICE:{drainApprovedEmailOutbox:async()=>({processed:1})}});
assert.equal(calls.length,3);assert.equal(ack,6);assert.equal(retry,0);
await consumeWake({messages:[msg('calendar')]},env);assert.equal(retry,1);
let drained=0;
assert.equal((await handleDrainWake({VISHAR_ENVIRONMENT:'staging',DRAIN:'true'},'DRAIN',async()=>drained++)).status,200);assert.equal(drained,0);
assert.equal((await handleDrainWake({VISHAR_ENVIRONMENT:'production',DRAIN:'true'},'DRAIN',async()=>drained++)).status,200);assert.equal(drained,1);
assert.equal(isWakeRequest(new Request('https://calendar.internal/internal/calendar/wake',{method:'POST'}),'calendar.internal','/internal/calendar/wake'),true);
assert.equal(isWakeRequest(new Request('https://calendar.vishartattoo.com/internal/calendar/wake',{method:'POST'}),'calendar.internal','/internal/calendar/wake'),false);
console.log('outbox wake boundary tests passed');
