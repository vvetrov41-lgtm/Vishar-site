import assert from 'node:assert/strict';
import {parseWake,receiveWake,consumeWake,handleDrainWake,isWakeRequest} from '../workers/lib/outbox-wake.js';
import {wakeAfterBookingRpc} from '../workers/lib/booking-wake-dispatch.js';
const now=Date.parse('2026-11-25T19:00:00Z');
const wakeUrl='https://outbox-wake.vishartattoo.com/internal/outbox/wake';
const crm='https://crm.vishartattoo.com';
const db='https://vfjexhfdbrjmuxfdvbdx.supabase.co';
const payload={lane:'calendar',due_ms:now};
assert.deepEqual(parseWake(payload,now),{lane:'calendar',delaySeconds:0});
assert.deepEqual(parseWake({...payload,due_ms:now+10000},now),{lane:'calendar',delaySeconds:11});
for(const bad of [{...payload,lane:'__proto__'},{...payload,client_id:'secret'},{...payload,due_ms:'bad'},{...payload,due_ms:now+301000}])assert.equal(parseWake(bad,now),null);
const sent=[];
const env={VISHAR_ENVIRONMENT:'production',OUTBOX_WAKE_ENABLED:'true',SUPABASE_URL:db,SUPABASE_PUBLISHABLE_KEY:'sb_publishable_test',OUTBOX_WAKE_QUEUE:{send:async(...args)=>sent.push(args)},OUTBOX_WAKE_RATE_LIMIT:{limit:async()=>({success:true})}};
const request=(token='a.b.c',origin=crm,url=wakeUrl)=>new Request(url,{method:'POST',headers:{authorization:'Bearer '+token,origin}});
let calls=0;
const upstream=async(url,init)=>{
  calls++;
  assert.equal(url,db+'/rest/v1/rpc/get_booking_outbox_wake_hints');
  assert.equal(init.headers.authorization,'Bearer a.b.c');
  assert.equal(init.redirect,'manual');
  return Response.json([payload]);
};
assert.equal((await receiveWake(request(),env,now,upstream)).status,202);
assert.deepEqual(sent,[[{lane:'calendar'},{delaySeconds:0}]]);
assert.equal((await receiveWake(request('bad'),env,now,upstream)).status,401);
assert.equal((await receiveWake(request(),{...env,OUTBOX_WAKE_ENABLED:'false'},now,upstream)).status,404);
assert.equal((await receiveWake(request('a.b.c','https://example.com'),env,now,upstream)).status,403);
assert.equal((await receiveWake(request('a.b.c',crm,'https://example.com/internal/outbox/wake'),env,now,upstream)).status,404);
assert.equal((await receiveWake(request(),env,now,async()=>new Response(null,{status:403}))).status,403);
assert.equal((await receiveWake(request(),env,now,async()=>Response.json([{...payload,lane:'unknown'}]))).status,503);
assert.equal((await receiveWake(request(),{...env,OUTBOX_WAKE_RATE_LIMIT:{limit:async()=>({success:false})}},now,upstream)).status,429);
assert.equal(calls,1);
assert.equal(sent.length,1);
// Network runtimes may expose a stream even when Content-Length is zero.
const streamRequest=(body,headers={})=>new Request(wakeUrl,{method:'POST',body,duplex:'half',headers:{authorization:'Bearer a.b.c',origin:crm,...headers}});
const emptyStream=()=>new ReadableStream({start(c){c.close();}});
assert.equal((await receiveWake(streamRequest(emptyStream()),env,now,upstream)).status,202);
assert.equal((await receiveWake(streamRequest(emptyStream(),{'content-length':'0'}),env,now,upstream)).status,202);
assert.equal((await receiveWake(streamRequest(emptyStream(),{authorization:''}),env,now,upstream)).status,401);
assert.equal((await receiveWake(streamRequest(new ReadableStream({start(c){c.enqueue(new Uint8Array([1]));c.close();}})),env,now,upstream)).status,400);
assert.equal((await receiveWake(streamRequest('x',{'content-length':'1'}),env,now,upstream)).status,400);
assert.equal(calls,3);
assert.equal(sent.length,3);
const preflight=await receiveWake(new Request(wakeUrl,{method:'OPTIONS',headers:{origin:crm,'access-control-request-method':'POST'}}),env,now,upstream);
assert.equal(preflight.status,204);assert.equal(preflight.headers.get('access-control-allow-origin'),crm);
const drainCalls=[];let ack=0,retry=0;
const msg=lane=>({body:{lane},ack(){ack++;},retry(options){assert.equal(options.delaySeconds,15);retry++;}});
const service={fetch:async(url,init)=>{drainCalls.push([url,init.method]);return Response.json({ok:true});}};
await consumeWake({messages:[msg('calendar'),msg('calendar'),msg('whatsapp'),msg('instagram'),msg('email'),msg('bad')]},{...env,CALENDAR_SERVICE:service,WHATSAPP_SERVICE:service,INSTAGRAM_SERVICE:service,GMAIL_SERVICE:{drainApprovedEmailOutbox:async()=>({processed:1})}});
assert.equal(drainCalls.length,3);assert.equal(ack,6);assert.equal(retry,0);
await consumeWake({messages:[msg('calendar')]},env);assert.equal(retry,1);
let drained=0;
assert.equal((await handleDrainWake({VISHAR_ENVIRONMENT:'staging',DRAIN:'true'},'DRAIN',async()=>drained++)).status,200);assert.equal(drained,0);
assert.equal((await handleDrainWake({VISHAR_ENVIRONMENT:'production',DRAIN:'true'},'DRAIN',async()=>drained++)).status,200);assert.equal(drained,1);
assert.equal(isWakeRequest(new Request('https://calendar.internal/internal/calendar/wake',{method:'POST'}),'calendar.internal','/internal/calendar/wake'),true);
assert.equal(isWakeRequest(new Request('https://calendar.vishartattoo.com/internal/calendar/wake',{method:'POST'}),'calendar.internal','/internal/calendar/wake'),false);
const waits=[];
const ctx={waitUntil:p=>waits.push(p)};
wakeAfterBookingRpc('gpt_schedule_appointment','a.b.c',env,ctx,async(url,init)=>{
 assert.equal(url,wakeUrl);assert.equal(init.headers.authorization,'Bearer a.b.c');return new Response(null,{status:202});
});
wakeAfterBookingRpc('gpt_list_appointments','a.b.c',env,ctx,()=>{throw Error('read must not wake');});
wakeAfterBookingRpc('gpt_schedule_appointment','a.b.c',{...env,VISHAR_ENVIRONMENT:'staging'},ctx,()=>{throw Error('staging must not wake');});
assert.equal(waits.length,1);await Promise.all(waits);
console.log('outbox wake boundary tests passed');
